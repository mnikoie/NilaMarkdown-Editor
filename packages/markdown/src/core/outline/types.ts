/**
 * مدلِ درختِ ساختار.
 *
 * ★ این تنها مدلِ درخت در کلِ پکیج است. هم پنلِ کناری از آن می‌خواند، هم
 * تاشدنِ داخلِ سند. اگر دو مدلِ جدا بسازیم، روزی از هم واگرا می‌شوند و
 * کاربر می‌بیند پنل یک چیز می‌گوید و سند چیزِ دیگر.
 *
 * ساختارِ گره عمداً با خروجیِ `structure_tree.py` هم‌شکل است (نوع/شماره/
 * عنوان/فرزندان) تا سندی که پایپ‌لاینِ ورود می‌سازد و درختی که ادیتور
 * می‌خواند یکی باشند.
 */
export interface OutlineNode {
  /** لنگرِ پایدار — هدفِ `:ref` و کلیدِ حالتِ تاشدگی. */
  id: string;
  /** `heading` یا نامِ directive: `ماده`، `تبصره`، `نکته`، … */
  kind: string;
  /** رتبهٔ عمق. کوچک‌تر = بیرونی‌تر. */
  level: number;
  title: string;
  /** `{شماره=۵۰}` — اگر بود. */
  number?: string;
  /** `{وضعیت=منسوخ}` — اگر بود. */
  status?: string;
  /** موقعیتِ گره در سندِ ProseMirror. */
  from: number;
  to: number;
  /** آیا این گره واقعاً محتوایی برای باز و بسته‌کردن دارد؟ */
  foldable: boolean;
  children: OutlineNode[];
}

export interface OutlineOptions {
  /**
   * وقتی سرفصل لنگرِ صریح (`{#id}`) ندارد، از روی متن ساخته می‌شود.
   * دو گره با عنوانِ یکسان نباید یک `id` بگیرند — وگرنه ارجاع به گرهِ
   * اشتباه می‌رود و تاشدنِ یکی، دیگری را هم می‌بندد.
   */
  slugify?: (text: string, index: number) => string;
}
