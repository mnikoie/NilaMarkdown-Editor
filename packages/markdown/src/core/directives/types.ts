/**
 * تعریفِ مارکِ سفارشی.
 *
 * این همان چیزی است که کاربر در UI می‌سازد و در دیتابیس ذخیره می‌شود. پکیج
 * نمی‌داند از کجا آمده — فقط یک `Record` می‌گیرد. به همین دلیل جابه‌جاییِ
 * محلِ ذخیره (فایل → دیتابیس) هیچ تغییری در این پکیج لازم ندارد.
 */

/** نوعِ گرهِ directive در mdast — هر سه توسطِ remark-directive پشتیبانی می‌شوند. */
export type DirectiveKind =
  /** `:::note{…}` … `:::` — محتوای بلوکی دارد */
  | "بلوکی"
  /** `:note[متن]{…}` — داخلِ یک پاراگراف */
  | "درون‌خطی"
  /** `::note{…}` — یک خطِ کامل، بی محتوا */
  | "برگی";

/** نوعِ داده‌ایِ یک صفت — برای ساختنِ خودکارِ فرمِ ویرایش. */
export type AttrType = "متن" | "عدد" | "تاریخ" | "گزینه‌ای" | "بولی";

export interface AttrSpec {
  /** نامِ صفت، همان‌طور که در متن نوشته می‌شود: `{نوع=…}` */
  name: string;
  /** برچسبِ فارسی در فرم. نبود = خودِ `name`. */
  label?: string;
  type: AttrType;
  required?: boolean;
  default?: string;
  /** فقط برای `گزینه‌ای`. */
  options?: string[];
}

/** شکلِ ظاهریِ کارت. */
export type MarkVariant =
  /** نوارِ رنگی در لبهٔ آغازین + پس‌زمینهٔ کم‌رنگ */
  | "نوار"
  /** کادرِ کامل با حاشیهٔ رنگی */
  | "کادر"
  /** بی‌کادر، فقط متنِ رنگی — کم‌سروصداترین */
  | "ساده"
  /** برچسبِ کوچکِ درون‌خطی (فقط برای مارکِ درون‌خطی معنی دارد) */
  | "برچسب";

export interface MarkDefinition {
  /** نامِ directive. در متن: `:::{name}`. یکتا. */
  name: string;
  /** برچسبِ نمایشی روی کارت: «نکتهٔ مؤلف». نبود = `name`. */
  label?: string;
  kind: DirectiveKind;

  /**
   * رنگِ پایه — یک رنگ، نه شش تا.
   *
   * پس‌زمینه و حاشیه و رنگِ متن با `color-mix` از همین ساخته می‌شوند، پس
   * تمِ روشن و تاریک هر دو خودکار درست درمی‌آیند. اگر شش رنگ از کاربر
   * بگیریم، کاربر در تمِ تاریک ترکیبِ ناخوانا می‌سازد.
   *
   * هر قالبِ معتبرِ CSS: `#f59e0b`، `oklch(70% .19 70)`، `tomato`.
   */
  color?: string;
  /** ایموجی یا یک کاراکتر. SVG نه — پکیج نباید کتابخانهٔ آیکون بیاورد. */
  icon?: string;
  variant?: MarkVariant;

  /** کارت خودش تاشو باشد. */
  collapsible?: boolean;
  /** اگر `collapsible`، حالتِ آغازین. پیش‌فرض: باز. */
  defaultOpen?: boolean;

  /**
   * عنوانِ کارت از کجا بیاید:
   *  - `برچسب` (پیش‌فرض) — همیشه `label`
   *  - `متن-تگ` — از `:::note[عنوانِ دلخواه]`
   *  - `خطِ اول` — اولین خطِ محتوا
   */
  titleFrom?: "برچسب" | "متن-تگ" | "خطِ اول";

  attrs?: AttrSpec[];

  /** شماره‌گذاریِ خودکار در سند: «نکته ۱»، «نکته ۲». */
  counter?: boolean;
  /** لنگرِ پایدار بگیرد، در درختِ ساختار بیاید و هدفِ `:ref` بشود. */
  anchor?: boolean;

  /** مثلاً `Mod-Alt-n`. */
  shortcut?: string;
  /** تایپِ `:::name` بلافاصله کارت بسازد. */
  inputRule?: boolean;
  /** در منوی `/` دیده شود. پیش‌فرض: true. */
  inSlashMenu?: boolean;

  /**
   * سطحِ این نوع در درختِ ساختار. کوچک‌تر = بیرونی‌تر.
   * فقط وقتی `anchor` است معنی دارد. مقادیر از `RANK`ِ پروتوتایپِ پایتون
   * می‌آیند تا دو مدلِ ناهماهنگ نسازیم.
   */
  rank?: number;
}

export type MarkRegistry = Record<string, MarkDefinition>;
