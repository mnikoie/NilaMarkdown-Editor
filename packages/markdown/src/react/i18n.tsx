const FA: Record<string, string> = {
  File: "فایل",
  Edit: "ویرایش",
  Insert: "درج",
  Format: "قالب",
  View: "نمایش",
  Paragraph: "پاراگراف",
};

export function translate(locale: MarkdownLocale, text: string): string {
  if (locale === "fa") return FA[text] ?? text;
  const direct = EN[text];
  if (direct) return direct;
  const heading = /^عنوانِ?\s*(\d+)$/.exec(text);
  if (heading) return `Heading ${heading[1]}`;
  const actualSize = /^اندازهٔ واقعی \((.+)٪\)$/.exec(text);
  if (actualSize) return `Actual Size (${actualSize[1]}%)`;
  return text;
}

interface I18nValue {
  locale: MarkdownLocale;
  t: (text: string) => string;
  number: (value: number) => string;
}

const I18nContext = createContext<I18nValue>({
  locale: "fa",
  t: (text) => translate("fa", text),
  number: (value) => value.toLocaleString("fa-IR"),
});

export function MarkdownI18nProvider({ locale, children }: { locale: MarkdownLocale; children: ReactNode }) {
  return (
    <I18nContext.Provider
      value={{
        locale,
        t: (text) => translate(locale, text),
        number: (value) => value.toLocaleString(locale === "fa" ? "fa-IR" : "en-US"),
      }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export function useMarkdownI18n(): I18nValue {
  return useContext(I18nContext);
}
